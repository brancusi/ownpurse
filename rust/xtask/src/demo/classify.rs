fn bt(org: &str, id: &str) -> Anchor {
    Anchor::line(org, DocType::BankTransaction, id, "L1")
}

fn mj(org: &str, id: &str, line: &str) -> Anchor {
    Anchor::line(org, DocType::ManualJournal, id, line)
}

fn ce(c: &str) -> impl Fn(ownpurse_core::classify::ClassifyError) -> String + '_ {
    move |x| format!("{c}: {x}")
}

fn at(hhmm: &str) {
    pin_clock(Some(&format!("2026-10-05T{hhmm}:00.000000Z")));
}

fn ctx(actor: Actor, batch: &str) -> WriteCtx {
    WriteCtx::new(actor, BatchId::new(batch))
}

/// Build `demo/classify.toml` and `demo/db/classify.sqlite` from the demo record.
pub fn build_classify(spec: &serde_json::Value, out: &mut Out) -> Result<()> {
    let toml = out.path("demo/classify.toml")?;
    std::fs::write(&toml, CLASSIFY_TOML).map_err(err("classify.toml"))?;
    let store = out.path("demo/db/classify.sqlite")?;
    let _ = std::fs::remove_file(&store);
    let rec = Record::open(out.root.join("demo/record.sqlite")).map_err(err("record"))?;
    let orgs = super::demo_tenants(spec)?;
    let paths = ClassifyPaths {
        config: toml,
        store: store.clone(),
    };
    let r = build(&paths, &rec, &orgs);
    pin_clock(None);
    r
}

fn build(paths: &ClassifyPaths, rec: &Record, orgs: &[(String, String)]) -> Result<()> {
    at("08:00");
    let mut ws =
        Workspace::open(paths, &ownpurse_core::view::View::main(rec), orgs).map_err(ce("open"))?;
    ws.suggest(
        &Filter::default(),
        &ctx(Actor::rule("engine"), "demo-suggest"),
    )
    .map_err(ce("suggest"))?;

    // the owner accepts the clear ones
    let human = Actor::human;
    at("08:10");
    let accepts = [
        bt("design", "bt-303"),
        bt("design", "bt-305"),
        bt("roast", "bt-106"),
        bt("roast", "bt-107"),
        bt("hold", "bt-202"),
        bt("hold", "bt-203"),
        mj("hold", "mj-204", "L1"),
        mj("roast", "mj-102", "L1"),
    ];
    for (i, a) in accepts.iter().enumerate() {
        ws.accept(a, &ctx(human(), &format!("demo-accept-{i}")))
            .map_err(ce("accept"))?;
    }
    at("08:20");
    let h = ctx(human(), "demo-set-1");
    ws.set_label(&bt("roast", "bt-101"), "treatment", "unknown", &h)
        .map_err(ce("set"))?;
    ws.accept(&bt("design", "bt-302"), &h)
        .map_err(ce("accept"))?;
    ws.set_label(&bt("design", "bt-302"), "treatment", "owner-paid", &h)
        .map_err(ce("set"))?;
    ws.set_label(&bt("design", "bt-301"), "should_be_account", "1530", &h)
        .map_err(ce("set"))?;

    // an agent batch, with a caption
    at("08:30");
    let ag = ctx(Actor::agent("claude"), "demo-agent-1")
        .caption("Cupping kit belongs to the cupping lab fit-out");
    let kit = [bt("lab", "bt-401"), bt("roast", "bt-111")];
    for (ty, v) in [
        ("project", "cupping"),
        ("bearer", "lab"),
        ("treatment", "owner-paid"),
    ] {
        ws.set_labels(&kit, ty, v, &ag).map_err(ce("agent set"))?;
    }

    // notes
    at("08:40");
    ws.add_note(
        &NoteTarget::Line(bt("roast", "bt-112")),
        "Fuel card or a personal fill-up? Ask before the close.",
        &ctx(human(), "demo-note-1"),
    )
    .map_err(ce("note"))?;
    ws.add_note(
        &NoteTarget::Line(bt("lab", "bt-401")),
        "Receipt lists 24 spoons and 180 sample cups.",
        &ctx(Actor::agent("claude"), "demo-note-2"),
    )
    .map_err(ce("note"))?;

    // groups
    at("08:45");
    let g = ctx(human(), "demo-group-1");
    let (_, chain) = ws
        .create_group("intercompany_chain", "Hollowpine proofs recharge", &g)
        .map_err(ce("group"))?;
    for (a, role) in [
        (bt("design", "bt-303"), "origin"),
        (mj("roast", "mj-101", "L1"), "mirror"),
        (bt("roast", "bt-108"), "settlement"),
        (bt("design", "bt-304"), "settlement"),
    ] {
        ws.add_member(&chain, &a, Some(role), &g)
            .map_err(ce("member"))?;
    }
    ws.add_note(
        &NoteTarget::Group(chain.clone()),
        "The November reprint is on Quillfeather's side only.",
        &g,
    )
    .map_err(ce("note"))?;
    let (_, split) = ws
        .create_group("split", "Emberline service visits", &g)
        .map_err(ce("group"))?;
    ws.add_member(&split, &bt("roast", "bt-105"), Some("origin"), &g)
        .map_err(ce("member"))?;
    ws.set_group_status(&split, "accountant", &g)
        .map_err(ce("status"))?;

    // a mistake, undone
    at("08:50");
    let m = ctx(human(), "demo-oops");
    ws.set_label(&bt("hold", "bt-206"), "project", "harvest", &m)
        .map_err(ce("set"))?;
    ws.undo_line(&bt("hold", "bt-206"), &m)
        .map_err(ce("undo"))?;

    // two labels set before a later sync changed their lines: they render stale (V19)
    at("08:55");
    let mut items = vec![];
    for (a, ty, v, field, then) in [
        (
            bt("design", "bt-308"),
            "project",
            "refit",
            "amount",
            "-212.83",
        ),
        (
            bt("roast", "bt-110"),
            "bearer",
            "roast",
            "date",
            "2025-10-14",
        ),
    ] {
        let line = ws
            .line(&a)
            .ok_or_else(|| format!("demo line {a} missing"))?;
        let mut fp = line.fingerprint.to_json();
        fp[field] = json!(then);
        items.push((
            EventKind::LabelSet,
            json!({"labels": [{"anchor": a.to_string(), "type": ty, "value": v, "source": "human",
                    "confidence": null, "evidence": [], "fingerprint": fp}]}),
        ));
    }
    drop(ws);
    let mut st = Store::open(&paths.store).map_err(ce("store"))?;
    st.append(&human(), &BatchId::new("demo-before-sync"), items)
        .map_err(ce("stale"))?;
    st.verify().map_err(ce("verify"))?;
    Ok(())
}
